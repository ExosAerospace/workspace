#!/usr/bin/env python3
"""gen_sent_review.py — build data/sent-review.json for the MC "Sent — needs task link" panel (option C).

Reads logs/sent-followup-log.json. For every contact WITHOUT a high-confidence task match (conf low/none),
computes a best-guess task by fuzzy-matching the send subject + contact name/org against task titles, and
writes a review row with a one-click 'suggested_task'. The MC panel lets Jon accept the suggestion (link)
or dismiss. Regenerated by the tracker / on demand.
"""
import json, os, re, urllib.request

WS = os.path.expanduser("~/.openclaw/workspace")
LOG = os.path.join(WS, "logs", "sent-followup-log.json")
OUT = os.path.join(WS, "mission-control", "data", "sent-review.json")
DISMISS = os.path.join(WS, "logs", "sent-review-dismissed.json")
SUPA = "https://pcrgpuoljylqcumijvnw.supabase.co/rest/v1"
KEY = json.load(open(os.path.expanduser("~/.openclaw/secrets.json")))["supabase_service_role_key"]
SH = {"apikey": KEY, "Authorization": "Bearer " + KEY}
STOP = set("re fw fwd the and for you your our exos meeting follow up call intro with from about ready draft send".split())


def supa(path):
    try:
        with urllib.request.urlopen(urllib.request.Request(SUPA + "/" + path, headers=SH), timeout=40) as r:
            return json.loads(r.read().decode() or "[]")
    except Exception:
        return []


def toks(s):
    return {w for w in re.split(r"[^a-z0-9]+", (s or "").lower()) if len(w) >= 4 and w not in STOP}


def main():
    contacts = json.load(open(LOG)).get("contacts", {})
    try: dismissed = set(json.load(open(DISMISS)))
    except Exception: dismissed = set()
    tasks = []; off = 0
    while True:
        c = supa(f"tasks?select=id,title,state&order=id.desc&limit=1000&offset={off}")
        tasks += c
        if len(c) < 1000: break
        off += 1000
    tt = [(t["id"], t.get("title", ""), t.get("state"), toks(t.get("title", ""))) for t in tasks]

    items = []
    for a, c in contacts.items():
        if c.get("conf") == "high" or a in dismissed:
            continue
        sug_id, sug_title, conf = c.get("task_id"), c.get("task_title"), c.get("conf")
        if not sug_id:  # NONE → fuzzy best-guess against task titles
            want = toks(c.get("subj", "")) | toks(c.get("name", "")) | {a.split("@")[-1].split(".")[0]}
            best = (0, None, None)
            for tid, title, state, ttok in tt:
                score = len(want & ttok)
                if score > best[0]:
                    best = (score, tid, title)
            if best[0] >= 2:
                sug_id, sug_title = best[1], best[2]
        items.append({
            "contact": a, "name": c.get("name", a), "subj": c.get("subj", ""),
            "last_sent": (c.get("last_sent") or "")[:10], "replied": bool(c.get("replied")),
            "suggested_task_id": sug_id, "suggested_title": (sug_title or "")[:70],
            "confidence": conf,
        })
    items.sort(key=lambda x: (x["suggested_task_id"] is None, x["last_sent"]), reverse=False)
    json.dump({"generated": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat(),
               "count": len(items), "items": items}, open(OUT, "w"), indent=2)
    withsug = sum(1 for i in items if i["suggested_task_id"])
    print(f"wrote {OUT}: {len(items)} review items, {withsug} with a suggested task")


if __name__ == "__main__":
    main()
