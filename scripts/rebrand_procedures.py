#!/usr/bin/env python3
"""rebrand_procedures.py — apply the Exos house branding (letterhead header + footer banners and a
clean Calibri base font) to EXISTING Process-Library .docx procedures IN PLACE, preserving their
content. For legacy/imported docs that were not generated by build_procedure.py and whose content
is not procedure-template-shaped, so we brand rather than restructure.

Usage:
  python3 scripts/rebrand_procedures.py <file.docx> [file2.docx ...]   # rebrand specific files
  python3 scripts/rebrand_procedures.py --render <file.docx>           # rebrand + write a PNG preview to /tmp
Each file is backed up to <file>.prebrand-YYYYMMDD before modification.
"""
import os, sys, shutil, datetime
from docx import Document
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

WS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEAD_IMG = os.path.join(WS, "mission-control", "brand-assets", "exos-letterhead-header.png")
FOOT_IMG = os.path.join(WS, "mission-control", "brand-assets", "exos-letterhead-footer.png")
BODY_FONT = "Calibri"
DARK = RGBColor(0x1c, 0x1c, 0x1c)


def _clear_hf(container):
    """Remove all runs/pictures from an existing header/footer so we don't stack banners."""
    for p in list(container.paragraphs):
        for r in list(p.runs):
            r._r.getparent().remove(r._r)
    # drop any tables an old letterhead may have used
    for t in list(getattr(container, "tables", []) or []):
        t._tbl.getparent().remove(t._tbl)


def rebrand(path):
    doc = Document(path)
    # Clean base typography (affects text using the default style; explicit runs keep their look)
    normal = doc.styles["Normal"]
    normal.font.name = BODY_FONT
    if not normal.font.size:
        normal.font.size = Pt(10.5)
    for sec in doc.sections:
        sec.top_margin = Inches(0.6); sec.bottom_margin = Inches(0.6)
        # Strip any letterhead we may have previously put in the Word header/footer — those sit in
        # the margin (bleed off the page) and are dropped by the docx->pdf converter MC uses.
        _clear_hf(sec.header); _clear_hf(sec.footer)

    # Banner in the BODY (top + bottom) so it renders cleanly in Word, Preview, AND Mission Control.
    if os.path.exists(HEAD_IMG):
        first = doc.paragraphs[0] if doc.paragraphs else doc.add_paragraph()
        bp = first.insert_paragraph_before()
        bp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        bp.paragraph_format.space_after = Pt(6)
        bp.add_run().add_picture(HEAD_IMG, width=Inches(5.0))
    if os.path.exists(FOOT_IMG):
        fb = doc.add_paragraph(); fb.alignment = WD_ALIGN_PARAGRAPH.CENTER
        fb.paragraph_format.space_before = Pt(10)
        fb.add_run().add_picture(FOOT_IMG, width=Inches(5.0))
    doc.save(path)


def main():
    args = [a for a in sys.argv[1:] if a != "--render"]
    render = "--render" in sys.argv
    if not args:
        print(__doc__); sys.exit(1)
    stamp = datetime.date.today().strftime("%Y%m%d")
    ok = 0
    for path in args:
        if not os.path.isfile(path):
            print("SKIP (missing):", path); continue
        try:
            # Preserve the TRUE original as a backup, and always rebrand FROM that original so
            # re-runs (e.g. resizing or repositioning the banner) never accumulate banners.
            import glob as _glob
            existing = sorted(_glob.glob(f"{path}.prebrand-*"))
            if existing:
                shutil.copy(existing[0], path)          # restore pristine original, then rebrand fresh
            else:
                shutil.copy(path, f"{path}.prebrand-{stamp}")
            rebrand(path)
            ok += 1
            print("REBRANDED:", os.path.relpath(path, WS))
            if render:
                out = "/tmp/rebrand_preview"
                os.makedirs(out, exist_ok=True)
                import subprocess
                subprocess.run(["qlmanage", "-t", "-s", "1100", "-o", out, path],
                               capture_output=True, timeout=60)
                print("  preview:", os.path.join(out, os.path.basename(path) + ".png"))
        except Exception as e:
            print("FAILED:", path, "->", str(e)[:120])
    print(f"\n{ok}/{len(args)} rebranded.")


if __name__ == "__main__":
    main()
